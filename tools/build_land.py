"""Convert Natural Earth ne_50m_land.geojson into land.js for the site.

Usage: python3 tools/build_land.py path/to/ne_50m_land.geojson > land.js

Output: window.LAND = [polygon, ...], where each polygon is a list of rings
(outer ring first, then holes) and each ring is a flat [lng, lat, lng, lat, ...]
list rounded to 0.01 degrees.
"""
import json
import sys

def ring_flat(ring):
    out = []
    prev = None
    for lng, lat in ring:
        pt = (round(lng, 2), round(lat, 2))
        if pt != prev:  # drop points that collapse together after rounding
            out.extend(pt)
            prev = pt
    return out

data = json.load(open(sys.argv[1]))
polys = []
for feature in data["features"]:
    geom = feature["geometry"]
    parts = [geom["coordinates"]] if geom["type"] == "Polygon" else geom["coordinates"]
    for part in parts:
        rings = [ring_flat(r) for r in part]
        rings = [r for r in rings if len(r) >= 6]
        if rings:
            polys.append(rings)

sys.stdout.write("// Generated by tools/build_land.py from Natural Earth 1:50m land (public domain).\n")
sys.stdout.write("window.LAND = ")
json.dump(polys, sys.stdout, separators=(",", ":"))
sys.stdout.write(";\n")
